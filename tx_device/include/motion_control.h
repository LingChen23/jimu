#ifndef MOTION_CONTROL_H
#define MOTION_CONTROL_H

#include <stdint.h>

#define MOTION_CONTROL_VERSION       1U
#define MOTION_CONTROL_HEADER_SIZE   4U
#define MOTION_RESPONSE_HEADER_SIZE  5U
#define MOTION_CONTROL_MAX_PAYLOAD   16U
#define MOTION_RESPONSE_MAX_PAYLOAD  48U
#define MOTION_RESPONSE_MAX_SIZE     \
    (MOTION_RESPONSE_HEADER_SIZE + MOTION_RESPONSE_MAX_PAYLOAD)

#define MOTION_CMD_START_STREAM 0x01U
#define MOTION_CMD_STOP_STREAM  0x02U
#define MOTION_CMD_GET_INFO     0x03U
#define MOTION_CMD_GET_STATUS   0x04U
#define MOTION_CMD_RESET_STATS  0x05U
#define MOTION_CMD_RECALIBRATE  0x06U
#define MOTION_CMD_REBOOT       0x07U

#define MOTION_RESULT_OK              0U
#define MOTION_RESULT_UNSUPPORTED     1U
#define MOTION_RESULT_BAD_PARAMETER   2U
#define MOTION_RESULT_BUSY            3U
#define MOTION_RESULT_NOT_ALLOWED     4U
#define MOTION_RESULT_DEVICE_OFFLINE  5U
#define MOTION_RESULT_GATEWAY_ERROR   6U

#define MOTION_STREAM_ACCEL      0x01U
#define MOTION_STREAM_GYRO       0x02U
#define MOTION_STREAM_COORDINATE 0x04U
#define MOTION_STREAM_ALL        \
    (MOTION_STREAM_ACCEL | MOTION_STREAM_GYRO | MOTION_STREAM_COORDINATE)

#define MOTION_REBOOT_CONFIRM 0xA5U

#define MOTION_STATUS_FLAG_STREAMING  0x01U
#define MOTION_STATUS_FLAG_CALIBRATED 0x02U
#define MOTION_STATUS_FLAG_SENSOR_OK  0x04U
#define MOTION_STATUS_FLAG_LOW_BATTERY 0x08U

#define MOTION_INFO_PAYLOAD_SIZE   14U
#define MOTION_STATUS_PAYLOAD_SIZE 29U

#endif
